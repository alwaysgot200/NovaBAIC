/**
 * 购买充值页（商业化方案 §5）：余额不足提示「充值」链接的落地页，
 * 内嵌 WebView 打开固定商城购买链接（[AccountApi.RECHARGE_URL]）。
 * 主题包装与 [AccountActivity] 同构（AppLocaleStore 语言 + Baic2Theme + 状态栏图标色），
 * 页面骨架走 AdvisorPage；WebView 写法镜像登录页的注册 WebView。
 */
@AndroidEntryPoint
class RechargeActivity : ComponentActivity() {

    @Inject
    lateinit var settingsRepository: SettingsRepository

    override fun attachBaseContext(newBase: Context) {
        val language = AppLocaleStore.readFrom(newBase)
        val tag = language.languageTag
        super.attachBaseContext(
            if (tag == null) newBase else newBase.withLocale(Locale.forLanguageTag(tag)),
        )
    }

    override fun onCreate(savedInstanceState: Bundle?) {
        enableEdgeToEdge()
        super.onCreate(savedInstanceState)
        setContent {
            val themeMode by settingsRepository.themeMode
                .collectAsStateWithLifecycle(initialValue = ThemeMode.SYSTEM)
            val accent by settingsRepository.accentColor
                .collectAsStateWithLifecycle(initialValue = AccentColor.BLUE)
            val darkTheme = when (themeMode) {
                ThemeMode.SYSTEM -> isSystemInDarkTheme()
                ThemeMode.LIGHT -> false
                ThemeMode.DARK -> true
            }
            val view = LocalView.current
            SideEffect {
                WindowCompat.getInsetsController(window, view).apply {
                    isAppearanceLightStatusBars = !darkTheme
                    isAppearanceLightNavigationBars = !darkTheme
                }
            }
            Baic2Theme(darkTheme = darkTheme, accent = accent) {
                RechargeScreen(onBack = { finish() })
            }
        }
    }
}

/** 购买充值 WebView 页：站点商城购买路由（需 JS/本地存储跑结算页）。 */
@SuppressLint("SetJavaScriptEnabled")
@Composable
private fun RechargeScreen(onBack: () -> Unit) {
    AdvisorPage(
        title = stringResource(R.string.float_recharge_title),
        onBack = onBack,
    ) { innerPadding ->
        AndroidView(
            modifier = Modifier
                .fillMaxSize()
                .padding(innerPadding),
            factory = { ctx ->
                WebView(ctx).apply {
                    settings.javaScriptEnabled = true
                    settings.domStorageEnabled = true
                    webViewClient = WebViewClient()
                    loadUrl(AccountApi.RECHARGE_URL)
                }
            },
        )
    }
}

private fun Context.withLocale(locale: Locale): Context {
    Locale.setDefault(locale)
    val configuration = Configuration(resources.configuration)
    configuration.setLocale(locale)
    configuration.setLayoutDirection(locale)
    return createConfigurationContext(configuration)
}
