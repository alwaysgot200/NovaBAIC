package com.verlintas.baic2.floatball.auto

import dagger.Binds
import dagger.Module
import dagger.hilt.InstallIn
import dagger.hilt.components.SingletonComponent
import javax.inject.Singleton

/**
 * v8 确定性回复通道的依赖绑定（托管方案 §二十四.4）：
 * [ReplyResolver] 依赖接口而非具体类，单测可注入 fake 修复调用。
 */
@Module
@InstallIn(SingletonComponent::class)
abstract class ReplyModule {

    @Binds
    @Singleton
    abstract fun bindReplyComposeSource(impl: ReplyComposer): ReplyComposeSource
}
